import type { Species } from './species'

export interface CellPos {
  x: number
  y: number
}

export type CellKind = 'rat' | 'crate'

export interface LevelCell extends CellPos {
  kind: CellKind
}

export interface LevelDef {
  id: number
  theme: Species
  timeLimit: number | null
  hintLimit: number
  tip: string
  cells: LevelCell[]
  start: CellPos
  end: CellPos
  solution: CellPos[]
}

function rats(points: CellPos[]): LevelCell[] {
  return points.map((p) => ({ ...p, kind: 'rat' as const }))
}

function crates(points: CellPos[]): LevelCell[] {
  return points.map((p) => ({ ...p, kind: 'crate' as const }))
}

